import assert from "node:assert/strict";
import fs from "node:fs";
import {presentFamilyPlayer360} from "../domain/family/FamilyPlayer360Presenter.js";
import {renderPlayerCompleteBoxScore} from "../views/reports/PlayerCompleteBoxScore.js";
const mk=(idx,props={})=>({date:"2026-10-"+String(idx+10).padStart(2,"0"),points:null,minutes:null,rebounds:null,assists:null,fg3_made:null,fg3_attempted:null,...props});
const onlyUnknown=presentFamilyPlayer360({recent_games:Array.from({length:8},(_,i)=>mk(i))});
assert.equal(onlyUnknown.enoughEvidence,false);
assert.match(onlyUnknown.evolution[0],/Faltan/);
assert.match(onlyUnknown.meaning[0],/No hay/);
const zeros=presentFamilyPlayer360({recent_games:Array.from({length:8},(_,i)=>mk(i,{points:0,minutes:10,rebounds:0,assists:0,fg3_made:0,fg3_attempted:5}))});
assert.equal(zeros.enoughEvidence,true);
assert.equal(zeros.trends.find(r=>r.key==="points")?.current,0);
const partial=presentFamilyPlayer360({recent_games:Array.from({length:8},(_,i)=>mk(i,{points:i===0?null:1,minutes:10,rebounds:0,assists:0}))});
assert.equal(partial.trends.some(r=>r.key==="points"),false);
const player={id:"playerA",first_name:"Prueba"};
const game={id:"gameA",date:"2026-10-21",opponent:"Oponente"};
const row={player_id:"playerA",game_id:"gameA",minutes:null,points:0,fg2_made:0,fg2_attempted:0,fg3_made:0,fg3_attempted:0,ft_made:0,ft_attempted:0};
const html=renderPlayerCompleteBoxScore({player,games:[game],stats:[row]});
assert.match(html,/N\/D/);
assert.match(html,/0 puntos/);
