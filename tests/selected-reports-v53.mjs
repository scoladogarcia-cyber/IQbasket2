import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {buildSelectedGamesSummary,renderSelectedGamesOverview} from "../views/reports/SelectedGamesOverviewV53.js";
import {BOX_HEADERS,buildBoxScoreExchangeRows,serializeBoxScoreCsv,serializeBoxScoreExcel,parseBoxScoreCsv,validateBoxScoreImport,commitBoxScoreImport} from "../services/reports/BoxScoreExchangeV53.js";
import {renderFinalGameReportV49} from "../views/reports/GameFinalReportV49Renderer.js";

const game={id:"g1",team_id:"t1",team_season_id:"ts1",team_score:8,opponent_score:6,opponent:"CB Coll",date:"2026-09-19"};
const game2={...game,id:"g2",team_score:5,opponent_score:10,opponent:"CB B"};
const player={id:"p1",first_name:"Manel",last_name:"—",jersey:0};
const stat={game_id:"g1",player_id:"p1",starter:true,minutes:30,points:8,fg2_made:4,fg2_attempted:6,fg3_made:0,fg3_attempted:2,ft_made:0,ft_attempted:0,off_reb:2,def_reb:1,assists:1,steals:0,blocks:0,turnovers:2,fouls_committed:1,fouls_drawn:0};
const s2={...stat,game_id:"g2",points:5,fg2_made:1,fg2_attempted:4,fg3_made:1,fg3_attempted:2,ft_made:0,ft_attempted:0};
const summary=buildSelectedGamesSummary([{game,stats:[stat]},{game:game2,stats:[s2]}]);
assert.equal(summary.rows.length,2);assert.equal(summary.scored,13);assert.equal(summary.conceded,16);
assert.equal(summary.totals.fg2m,5);assert.equal(summary.totals.fg2a,10);
const overview=renderSelectedGamesOverview([{game,stats:[stat]},{game:game2,stats:[s2]}]);
assert.match(overview,/Resumen visual/);assert.match(overview,/50\.0%/);assert.match(overview,/Comparación de puntos/);
assert.doesNotMatch(overview,/El equipo gana cuando|causa de la derrota/);
const missing=buildSelectedGamesSummary([{game,stats:[stat]},{game:{...game2,opponent_score:null},stats:null}]);
assert.equal(missing.scored,null);assert.equal(missing.totals,null);
assert.match(renderSelectedGamesOverview([{game,stats:[stat]},{game:{...game2,opponent_score:null},stats:null}]),/N\/D/);
const rows=buildBoxScoreExchangeRows([{game,stats:[stat],players:[player]}]);
assert.equal(rows[0].player_id,"p1");assert.equal(rows[0].game_id,"g1");
const csv=serializeBoxScoreCsv(rows),matrix=parseBoxScoreCsv(csv);
assert.deepEqual(matrix[0],BOX_HEADERS);assert.equal(matrix[1][2],"p1");
assert.match(serializeBoxScoreExcel(rows),/Workbook/);
const valid=validateBoxScoreImport(matrix,{game,stats:[stat],eligiblePlayers:[player]});
assert.equal(valid.points,8);assert.equal(valid.differences,0);
const changed=matrix.map(row=>[...row]);changed[1][BOX_HEADERS.indexOf("minutes")]="29";
assert.equal(validateBoxScoreImport(changed,{game,stats:[stat],eligiblePlayers:[player]}).differences,1);
const tampered=matrix.map(row=>[...row]);tampered[1][0]="other";
assert.throws(()=>validateBoxScoreImport(tampered,{game,stats:[stat],eligiblePlayers:[player]}),/no válido/);
assert.throws(()=>validateBoxScoreImport(matrix,{game,stats:[stat],eligiblePlayers:[]}),/no válido/);
const badShot=matrix.map(row=>[...row]);badShot[1][BOX_HEADERS.indexOf("fg2_made")]="7";
assert.throws(()=>validateBoxScoreImport(badShot,{game,stats:[stat],eligiblePlayers:[player]}),/no concuerdan/);
assert.throws(()=>validateBoxScoreImport([matrix[0]],{game,stats:[stat],eligiblePlayers:[player]}),/partido completo/);
const denied={can:()=>false};
await assert.rejects(commitBoxScoreImport({preview:valid,client:{from:()=>{throw Error("must not query")}},auth:denied,game,eligiblePlayers:[player]}),/permisos/);
const source=readFileSync(new URL("../views/ReportsViewV53.js",import.meta.url),"utf8");
assert.match(source,/class ReportsViewV53 extends ReportsViewV50/);
assert.match(source,/select\("game_id,player_id,action_type,made,points,coord_x,coord_y"\)/);
assert.match(source,/\.in\("game_id",ids\.slice/);
assert.match(source,/playerIds\.has\(id\(event\.player_id\)\)/);
assert.match(source,/_getGameShotEvents\(gameId=null,playerId=null\)/);
assert.match(source,/this\._playerEventsScope/);
assert.match(source,/renderSelectedGamesOverview/);
assert.match(source,/commitBoxScoreImport/);
const registry=readFileSync(new URL("../services/LazyViewRegistry.js",import.meta.url),"utf8");
assert.match(registry,/new ReportsViewV53\(authController\)/);
const renderer=renderFinalGameReportV49({game,teamName:"Manyanet",players:[player],stats:[stat],events:[],periods:[]});
assert.ok(renderer.indexOf("El partido en un vistazo")<renderer.indexOf("Acta individual completa"));
assert.match(renderer,/Guía de lectura/);
console.log("SELECTED_REPORTS_V53_OK: muestra real, PDF antes del acta, mapas individuales con lectura fresca, CSV/Excel e importación validada");
