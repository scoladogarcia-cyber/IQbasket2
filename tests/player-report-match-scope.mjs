import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { selectPlayerReportGames, filterPlayerReportShots, playerReportSelectionKey } from "../services/reports/PlayerReportMatchScope.js";
import { renderPlayerCompleteBoxScore } from "../views/reports/PlayerCompleteBoxScore.js";
import { loadAuthorizedPlayerSeasonStats, replaceScopedPlayerStatsInMemory } from "../services/reports/PlayerSeasonReadService.js";

const player = {id:"p1",team_id:"t"};
const games = [{id:"g1",team_id:"t",team_season_id:"s",opponent:"Rival A"},{id:"g2",team_id:"t",team_season_id:"s",opponent:"Rival B"}];
const row=(game_id,points,fg2_made,fg2_attempted,blocks_received)=>({game_id,player_id:"p1",points,minutes:20,fg2_made,fg2_attempted,fg3_made:0,fg3_attempted:0,ft_made:0,ft_attempted:0,blocks_received});
const rows=[row("g1",8,4,5,2),row("g2",20,10,12,0),{...row("g1",99,1,1,0),player_id:"other"}];
const selection=selectPlayerReportGames(games,"g1");
assert.deepEqual(selection,[games[0]]);
assert.deepEqual(selectPlayerReportGames(games,"all"),games);
assert.throws(()=>selectPlayerReportGames(games,"missing"),/no está disponible/);
assert.throws(()=>selectPlayerReportGames([games[0],games[0]],"g1"),/no está disponible/);
assert.throws(()=>selectPlayerReportGames(games,""),/válido/);
const html=renderPlayerCompleteBoxScore({player,games:selection,stats:rows});
assert.match(html,/8 puntos, 20 minutos/);
assert.match(html,/4\/5/);
assert.match(html,/80\.0%/);
assert.match(html,/TAP REC\./);
assert.doesNotMatch(html,/Rival B|10\/12|28 puntos|99 puntos|TEMPORADA/);
const season=renderPlayerCompleteBoxScore({player,games,stats:rows});
assert.match(season,/28 puntos, 40 minutos/);
assert.match(season,/14\/17/);
assert.match(season,/Rival B/);
const events=[{game_id:"g1",id:1},{game_id:"g2",id:2},{gameId:"g1",id:3},{id:4}];
assert.deepEqual(filterPlayerReportShots(events,selection).map(e=>e.id),[1,3]);
assert.notEqual(playerReportSelectionKey({players:[player],games:selection}),playerReportSelectionKey({players:[player],games}));
let gameQuery;
const db={from(table){assert.equal(table,"player_game_stats");return {select(){return {in(k,v){if(k==="game_id")gameQuery=v;else assert.deepEqual(v,["p1"]);return this;},range(){return Promise.resolve({data:[rows[0]],error:null});}};}};}};
const stats=await loadAuthorizedPlayerSeasonStats({supabase:db,policy:{canView:()=>true},context:{teamId:"t",teamSeasonId:"s"},players:[player],games:selection});
assert.deepEqual(gameQuery,["g1"]);
const store={playerGameStats:[...rows]};
replaceScopedPlayerStatsInMemory(store,{players:[player],games:selection,stats});
assert.equal(store.playerGameStats.length,3);
assert.ok(store.playerGameStats.includes(rows[1]));
assert.ok(store.playerGameStats.includes(rows[2]));
const source=path=>readFileSync(new URL("../"+path,import.meta.url),"utf8");
const v50=source("views/ReportsViewV50.js"), v53=source("views/ReportsViewV53.js"), legacy=source("views/ReportsViewLegacyV36.js");
assert.match(v50,/selectPlayerReportGames\(this\._getFilteredGames\(\), this\.selectedGameId\)/);
assert.match(v50,/select-player-game/);
assert.match(v50,/super\._renderPlayerReport\(selection\.players, selection\.games\)/);
assert.match(v50,/this\._isCurrentPlayerSelection\(selection, context\)/);
assert.match(legacy,/filterPlayerReportShots\(this\._getGameShotEvents\(null, player\.id\), allGames\)/);
assert.match(v53,/Fichas individuales de este partido/);
assert.match(v53,/token!==this\._playerReadToken/);
console.log("PASS: exact match scope, season totals, shot maps, stale selections, fresh read and cache isolation.");
